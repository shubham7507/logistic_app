import assert from 'node:assert/strict';
import {SEED} from '../js/mock-data.js';
import * as HR from '../js/store-hr.js';
import * as T from '../js/staff-time.js';
import * as W from '../js/grocery-workforce.js';
import * as B from '../js/seller-branches.js';
import * as PC from '../js/people-core.js';
import * as Payroll from '../js/payroll-core.js';
const s=structuredClone(SEED),store='grocery',pid='PICK-001';
const day=new Date().toISOString().slice(0,10),next=n=>new Date(Date.parse(day+'T12:00:00Z')+n*86400000).toISOString().slice(0,10);
const working=Array.from({length:7},(_,i)=>next(i)).find(d=>new Date(d+'T12:00:00Z').getUTCDay()!==0);
const future=Array.from({length:7},(_,i)=>next(i+1)).find(d=>new Date(d+'T12:00:00Z').getUTCDay()!==0);
const worker=HR.screen(s,'myHR','picker');
assert.match(worker,/Request leave/);assert.match(worker,/demo template/);
assert.equal(T.schedule(s,pid,day)?.by,'Demo workweek');
assert.equal(T.requestLeave(s,store,pid,{from:future,to:future,units:1,reason:'Family event'}),'');
s.hrTab='time';
assert.match(HR.screen(s,'storeHR',store),/Family event/);
assert.equal(T.decideLeave(s,store,s.staffLeaveRequests.at(-1).id,'approve','paid','ABC Grocery'),'');
if(working===day){
 assert.equal(T.checkIn(s,store,pid,'grocery-B1'),'');
 assert.equal(s.staffDays.at(-1).status,'pending');
 assert.equal(T.decideAttendance(s,store,s.staffDays.at(-1).id,'approve','ABC Grocery'),'');
}
assert.equal(B.addBranch(s,store,'Test West Store','20 Market Road, New Delhi 110005','West Delhi'),'');
const newBranch=B.branchesFor(s,store).at(-1);
assert.equal(B.selectBranch(s,store,newBranch.id),'');
assert.match(B.branchScreen(s,store),/Test West Store/);
assert.match(W.scheduleScreen(s,store),/No active staff assigned here/);
assert.equal(PC.requestCover(s,store,{empId:'EMP-PICK-001',toBranch:newBranch.id,date:future,reason:'Launch'}),'');
assert.equal(s.coverRequests[0].status,'approved');
assert.match(W.scheduleScreen(s,store),/Asha Picker/);
assert.equal(PC.createTeam(s,store,{branchId:newBranch.id,template:'morning'}),'');
assert.equal(PC.teamMember(s,store,s.teams.at(-1).id,'EMP-PICK-001','add'),'');
assert.match(PC.screen(s,'branchesTeams',store),/Morning preparation/);
const shiftDay=future===day?next(1):future;
assert.equal(W.publishPickerShift(s,store,pid,shiftDay,'09:00','17:00'),'');
const shift=s.pickerSchedules.at(-1);assert.match(W.pickerScheduleScreen(s,'picker'),/Request cover/);
assert.equal(W.respondPickerShift(s,'picker',shift.id,'cover'),'');
assert.ok(s.notifications.some(n=>n.to===store&&n.route==='shopSchedule'&&n.ref===shift.id));
const replacement={id:'PICK-DEMO',store,name:'Demo Cover',mobile:'9876505199',status:'active',branchIds:[newBranch.id],payPlan:{type:'daily',rate:400}};
s.pickerStaff.push(replacement);
assert.match(W.scheduleScreen(s,store),/Approve cover & notify/);
assert.equal(W.reassignPickerShift(s,store,shift.id,replacement.id),'');
assert.equal(shift.pickerId,replacement.id);
assert.match(W.pickerScheduleScreen(s,'picker'),/No scheduled shifts/);
// Seller keeps the accepted leave; the mock clock enables a safe month-end review.
const end=T.advanceDemoToMonthEnd(s);
const m=end.slice(0,7);
assert.equal(T.lockMonth(s,store,m,'ABC Grocery'),'');
assert.equal(HR.postEarnings(s,store),'');
Payroll.ensurePayrollCore(s);
const emp=s.employments.find(e=>e.business===store&&e.source.id===pid);
assert.ok(Payroll.balance(s,emp.personId)>0);
assert.equal(HR.setPayout(s,pid,{method:'bank',account:'12345678901',ifsc:'SBIN0001234',name:'Asha Picker'}),'');
const run=Payroll.runMonthlyPayroll(s,store,m);
assert.ok(run.lines.some(l=>l.personId===emp.personId&&l.verified&&l.amount>0));
assert.match(Payroll.monthlyPayrollScreen(s,store,m),/Submit mock bank batch/);
const result=Payroll.approveMonthlyPayroll(s,run.id);
assert.equal(result.ok,true);
assert.ok(result.results.some(r=>r.personId===emp.personId&&r.outcome==='paid'));
assert.equal(Payroll.balance(s,emp.personId),0);
globalThis.__moveaiClockOffset=0;
console.log('PASS staff repair: leave, check-in approval, branch, team template, cover, shift, month-end and mock GIRO');
