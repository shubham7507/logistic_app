const s=structuredClone(SEED),business='fashion',period=new Date().toISOString().slice(0,7);
s.pickerStaff.push({id:'PICK-SANJU',store:business,name:'Sanju Cashier',mobile:'9876505199',status:'active',payPlan:{type:'monthly',rate:6000}});
PC.ensureCore(s);Pay.ensurePayrollCore(s);
