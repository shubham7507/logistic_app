assert.equal(Pay.confirmPayment(s,upiEntry.id,'owner',true),'');
assert.equal(Pay.balance(s,pooja.personId,business),8000);
assert.equal(Pay.confirmPayment(s,upiEntry.id,'worker',true),'');
