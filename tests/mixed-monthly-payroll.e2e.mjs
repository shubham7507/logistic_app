try{Commerce.bind(fakeRoot,{getState:()=>s,save:()=>saved++,render:()=>{},toast:x=>{toasted=x;},navigate:()=>{}});cashButton.onclick();}
finally{globalThis.confirm=previousConfirm;}
assert.equal(saved,1);assert.match(toasted,/Waiting for worker confirmation/);
assert.match(Pay.startPayrollPayment(s,run.id,sanju.personId).error,/not waiting/);
assert.equal(Pay.balance(s,sanju.personId,business),6000);
assert.match(Pay.monthlyPayrollScreen(s,business,period),/awaiting worker receipt/);
