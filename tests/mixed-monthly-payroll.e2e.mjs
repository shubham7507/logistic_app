const run=Pay.runMonthlyPayroll(s,business,period);
assert.equal(Pay.setPayrollMethod(s,run.id,sanju.personId,'cash'),'');
assert.equal(Pay.setPayrollMethod(s,run.id,pooja.personId,'upi'),'');
let draft=Pay.monthlyPayrollScreen(s,business,period);
assert.match(draft,/Approve payday · ₹24,000/);
assert.match(draft,/Pay by/);
assert.equal(Pay.runMonthlyPayroll(s,business,period).id,run.id);
const result=Pay.approveMonthlyPayroll(s,run.id);
assert.equal(result.ok,true);
assert.deepEqual(result.results.map(r=>r.outcome).sort(),['awaiting_cash','awaiting_upi','paid']);
assert.equal(Pay.balance(s,asha.personId,business),0);
assert.equal(Pay.balance(s,pooja.personId,business),8000);
assert.equal(Pay.balance(s,sanju.personId,business),6000);
assert.equal(Pay.runMonthlyPayroll(s,business,period).id,run.id,'pending handovers block duplicate run');
assert.match(Pay.monthlyPayrollScreen(s,business,period),/Paid ₹10,000 · waiting ₹14,000/);
assert.match(Commerce.screen(s,'monthlyPayroll',business),/Monthly payroll/);
s.currentWorkspace=business;
const cashButton={dataset:{payrollStart:run.id,person:sanju.personId}};
const fakeRoot={querySelectorAll:q=>q==='[data-payroll-start]'?[cashButton]:[],querySelector:()=>null};
