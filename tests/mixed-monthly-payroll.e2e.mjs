const asha=find('PICK-004'),pooja=find('MGR-004'),sanju=find('PICK-SANJU');
assert.ok(asha&&pooja&&sanju);
for(const e of [asha,pooja,sanju])e.payPlan={type:'monthly',rate:10000};
