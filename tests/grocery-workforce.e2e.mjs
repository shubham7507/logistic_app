okay(W.selectStoreManager(s,'groceryManager','MGR-001'));

okay(Staff.invitePicker(s,'grocery','Priya Cover','9876501199'));
const cover=s.pickerStaff.at(-1);
okay(Staff.selectPicker(s,'picker',cover.id));okay(Staff.acceptPickerInvite(s,'picker'));okay(Pay.setPickerPayPlan(s,'grocery',cover.id,'daily',500));
assert.match(W.publishPickerShift(s,'groceryFreshManager',cover.id,today,'09:00','17:00'),/Choose an active picker/);
okay(W.publishPickerShift(s,'groceryManager',cover.id,today,'09:00','17:00'));
const roster=s.pickerSchedules.at(-1);
assert.match(Pay.startPickerShift(s,'picker'),/Confirm your scheduled shift/);
okay(W.respondPickerShift(s,'picker',roster.id,'cover'));
assert.match(Pay.startPickerShift(s,'picker'),/Confirm your scheduled shift/);
assert.match(W.reassignPickerShift(s,'groceryFreshManager',roster.id,'PICK-001'),/unavailable/);
okay(W.reassignPickerShift(s,'groceryManager',roster.id,'PICK-001'));
assert.equal(roster.pickerId,'PICK-001');
assert.match(C.screen(s,'pickSchedule','picker'),/No scheduled shifts/);
okay(Staff.selectPicker(s,'picker','PICK-001'));
okay(W.respondPickerShift(s,'picker',roster.id,'confirm'));
okay(Pay.startPickerShift(s,'picker'));okay(Pay.endPickerShift(s,'picker'));
const shift=s.pickerShifts.at(-1);
okay(W.requestPickerTimeCorrection(s,'picker',shift.id,'09:15','17:15','Clocked in late'));
const correction=s.pickerTimeCorrections.at(-1);
assert.match(Pay.approvePickerShift(s,'groceryManager',shift.id),/Resolve the time correction/);
assert.match(W.decidePickerTimeCorrection(s,'groceryFreshManager',correction.id,true),/unavailable/);
okay(W.decidePickerTimeCorrection(s,'groceryManager',correction.id,true));
assert.match(shift.startAt,/T09:15/);
okay(Pay.approvePickerShift(s,'groceryManager',shift.id));
assert.match(Pay.createPickerPayRun(s,'groceryManager','PICK-001'),/store access/);
assert.match(C.screen(s,'managerTimecards','groceryManager'),/Picker timecards/);
okay(Pay.createPickerPayRun(s,'grocery','PICK-001'));
const pay=s.pickerPayRuns.at(-1);okay(Pay.approvePickerPayRun(s,'grocery',pay.id));
assert.match(W.finalizePickerOffboarding(s,'grocery','PICK-001'),/Plan or revoke/);
okay(W.planPickerOffboarding(s,'grocery','PICK-001',today,'Voluntary exit'));
assert.match(W.finalizePickerOffboarding(s,'grocery','PICK-001'),/Resolve open tasks/);
okay(Pay.recordPickerPayment(s,'grocery',pay.id,'bank','TEST-FINAL-001'));

// Full customer order through the manager, picker, seller/courier and admin.
const placed=Orders.placeOrder(s,{productId:'PRD-101',qty:2,address:'Noida',method:'upi',vpa:'test@okaxis'}).order;
assert.match(C.sellerAction(s,'groceryFreshManager',placed.id,'accept'),/denied/);
okay(C.sellerAction(s,'groceryManager',placed.id,'accept'));
okay(Staff.assignPicker(s,'groceryManager',placed.id,'PICK-001'));
assert.match(W.finalizePickerOffboarding(s,'grocery','PICK-001'),/Resolve open tasks/);
okay(C.pickerAction(s,'picker',placed.id,'start'));
for(const item of placed.items)okay(C.pickerAction(s,'picker',placed.id,'check',item.productId));
okay(C.pickerAction(s,'picker',placed.id,'complete'));
okay(C.sellerAction(s,'groceryManager',placed.id,'pack',1));
assert.equal(placed.deliveryAssignment.partnerName,'Ravi Delivery');
okay(C.deliveryAction(s,'deliveryPartner',placed.id,'accept'));
