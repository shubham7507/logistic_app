import assert from 'node:assert/strict';
import {SEED} from '../js/mock-data.js';
import {allowedRoutes} from '../js/config.js';
import {mobileNavigation} from '../js/navigation.js';
import * as W from '../js/grocery-workforce.js';
import * as Staff from '../js/grocery-staff.js';
import * as Pay from '../js/grocery-picker-pay.js';
import * as C from '../js/commerce.js';
import * as Orders from '../js/product-orders.js';

const s=structuredClone(SEED),today=new Date().toISOString().slice(0,10);
const okay=(result)=>assert.equal(result,'');
assert.ok(allowedRoutes('groceryManager').has('shopSchedule'));
assert.ok(!allowedRoutes('groceryManager').has('shopPickerPay'));
assert.ok(!allowedRoutes('groceryManager').has('shopOffboarding'));
assert.ok(allowedRoutes('picker').has('pickSchedule'));
assert.deepEqual(mobileNavigation('seller','groceryManager',[['home','Home'],['shopOrders','Orders'],['shopSchedule','Schedule'],['managerTimecards','Timecards']]).shown.map(x=>x[0]),['home','shopOrders','shopSchedule','managerTimecards']);
assert.match(C.screen(s,'shopTeam','grocery'),/Invite a branch manager/);
assert.match(C.screen(s,'managerProfile','groceryManager'),/Maya Manager/);
assert.match(C.screen(s,'shopSchedule','groceryManager'),/Publish shift/);
assert.match(C.screen(s,'pickSchedule','picker'),/My schedule/);
assert.match(C.screen(s,'commercePartners','admin'),/Managers/);

okay(W.inviteStoreManager(s,'grocery','Nina Supervisor','9876501299'));
const invited=s.storeManagers.at(-1);
assert.match(W.inviteStoreManager(s,'groceryFresh','Duplicate','9876501299'),/already in use/);
assert.match(W.acceptStoreManager(s,'groceryManager'),/No manager invitation/);
okay(W.selectStoreManager(s,'groceryManager',invited.id));
assert.match(C.screen(s,'shopSchedule','groceryManager'),/Accept manager invitation/);
okay(W.acceptStoreManager(s,'groceryManager'));
