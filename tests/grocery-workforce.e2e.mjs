assert.equal(s.pickerStaff[0].status,'offboarded');
assert.match(Pay.startPickerShift(s,'picker'),/Active picker/);
assert.match(C.screen(s,'shopOffboarding','grocery'),/completed/);
assert.match(C.screen(s,'commercePartners','admin'),/offboarded/);
assert.match(C.sellerAction(s,'groceryManager',placed.id,'pack',1),/current stage/);
okay(W.removeStoreManager(s,'grocery','MGR-001'));
assert.match(C.sellerAction(s,'groceryManager',placed.id,'accept'),/denied/);
console.log(JSON.stringify({status:'PASS',suite:'Manager invitation, shift cover, time correction, final pay, picker exit, full grocery fulfilment',order:placed.id,manager:invited.name,picker:s.pickerStaff[0].status}));
